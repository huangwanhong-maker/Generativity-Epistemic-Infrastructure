namespace {
int checks = 0;
void check(bool value, const char *reason) {
    ++checks;
    if (!value)
        throw std::runtime_error(reason);
}
template <class F> void fails(const char *code, F &&function) {
    try {
        function();
    } catch (const gr::Error &error) {
        check(error.code == code, (std::string("Expected ") + code + ", got " + error.code).c_str());
        return;
    }
    throw std::runtime_error(std::string("Expected error: ") + code);
}
Value raw(Bytes bytes) {
    return Value::bytes("gr.bytes@1", std::move(bytes));
}
std::string text(const Value &value) {
    return {value.as_bytes().begin(), value.as_bytes().end()};
}
ImplementationDescriptor provider(std::string id, const OperationDescriptor &operation) {
    return {std::move(id), operation.id, operation.fingerprint(), {"cpu.sequential", "cpu.threaded"},
            {"cpu"},       {"host"},     operation.determinism,   true,
            Json::object()};
}
void type_contracts() {
    ValueTypeRegistry types;
    for (auto id : {"missing-version", "name@1", "x..y@1", "x.y@", "x.y@@1", "x.y@1 2", ".x.y@1"})
        fails("qualified_id", [&] { validate_qualified_id(id); });
    validate_qualified_id("example.future_type@2026.1");
    types.validate(Value::json("gr.json@1", Json{{"n", 2}}));
    fails("representation", [&] { types.validate(Value::json("gr.bytes@1", 1)); });
    fails("unknown_value_type", [&] { types.validate(Value::json("future.structure@1", Json::object())); });
    fails("unsupported_value", [&] { types.validate(Value::json("gr.json@1", 0.5)); });
    fails("value_constraint", [&] { types.validate(Value::bytes("gr.sha256-hex@1", Bytes(64, 'Z'))); });
    fails("type_constraints", [&] {
        types.register_type({"test.typo@1", Representation::Bytes, "Bad constraints", {{"max_bytez", 4}}});
    });
    fails("type_constraints", [&] {
        types.register_type({"test.bounds@1",
                             Representation::Bytes,
                             "Conflicting bounds",
                             {{"min_bytes", 5}, {"max_bytes", 2}}});
    });
    fails("type_constraints", [&] {
        types.register_type({"test.mixed@1",
                             Representation::Json,
                             "Conflicting implied kinds",
                             {{"required_keys", Json::array({"x"})}, {"min_items", 2}}});
    });
    fails("type_constraints", [&] {
        types.register_type(
            {"test.bad-size@1", Representation::Bytes, "Negative count", {{"max_bytes", -1}}});
    });
    fails("type_constraints", [&] {
        types.register_type({"test.bad-keys@1",
                             Representation::Json,
                             "Duplicate keys",
                             {{"required_keys", Json::array({"x", "x"})}}});
    });
    auto original = types.describe("gr.bytes@1");
    fails("duplicate_type", [&] { types.register_type(original); });
    auto copy = original;
    copy.meaning = "Altered meaning";
    check(original.fingerprint() != copy.fingerprint(), "Type descriptor identity includes declared meaning");
    check(types.describe(original.id).meaning == original.meaning,
          "Caller mutation cannot alter registered descriptor");
    types.register_type({"test.small-int@1",
                         Representation::Json,
                         "An exact integer from -5 to 5",
                         {{"kind", "integer"}, {"min_value", -5}, {"max_value", 5}}});
    types.validate(Value::json("test.small-int@1", -5));
    fails("value_constraint", [&] { types.validate(Value::json("test.small-int@1", 6)); });
}
void sha_conformance() {
    ValueTypeRegistry types;
    gr::kernel::OperationRegistry operations;
    ImplementationRegistry implementations;
    install_cpu_implementations(implementations, operations);
    SequentialBackend serial;
    ThreadedCpuBackend threaded;
    ExecutionOptions options;
    options.max_threads = 4;
    // Independently generated with Python hashlib over bytes((i*37+11)%256),
    // covering SHA-256 block and provider chunk boundaries. These expected values
    // are not generated by either provider under assessment.
    const std::vector<std::pair<std::size_t, std::string>> vectors{
        {0, "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"},
        {1, "e7cf46a078fed4fafd0b5e3aff144802b853f8ae459a4f0c14add3314b7cc3a6"},
        {63, "5f6401b96532c36de4e65beec0409b69b1d181864c8009b7a04f43e5d56350d1"},
        {64, "94eb5de4943613fd048dc93393ab06877405faa39c11f53e9386083339833e7e"},
        {65, "fc518669b6eb4b4dd91827ecacef86689c725bd5bab888fd3b26dbb196eec954"},
        {4095, "14247e71abeac04b1bb56818238f449fe1339e1d9b347ade9224b12460f39d1c"},
        {4096, "4e441a3533bb2c10cd5649981d395744213e09a336746b5a3458fee4057205ec"},
        {4097, "042a02b55ba342cdd30322331816b6e4bca073f33bdb80149dc74a6f949802f4"},
        {65536, "6fc179cfd193754e6109ad043f56d146c7e7d7c3623ffceae318266286f58388"}};
    Batch batch;
    for (const auto &[length, expected] : vectors) {
        (void)expected;
        Bytes bytes(length);
        for (std::size_t i = 0; i < length; ++i)
            bytes[i] = static_cast<std::uint8_t>((i * 37 + 11) % 256);
        batch.push_back({raw(std::move(bytes))});
    }
    for (const auto *backend :
         {static_cast<const ExecutionBackend *>(&serial), static_cast<const ExecutionBackend *>(&threaded)})
        for (auto implementation : {"gr.cpu.sha256.oneshot@1", "gr.cpu.sha256.incremental@1"}) {
            const auto result = backend->execute(types, operations, implementations, "gr.bytes.sha256@1",
                                                 implementation, batch, options);
            for (std::size_t i = 0; i < vectors.size(); ++i)
                check(text(result.outputs[i][0]) == vectors[i].second, "Independent SHA-256 expected vector");
        }
    std::mt19937 random(0x47524f53);
    Batch generated;
    for (int i = 0; i < 128; ++i) {
        Bytes bytes(random() % 10000);
        for (auto &byte : bytes)
            byte = static_cast<std::uint8_t>(random() & 255);
        generated.push_back({raw(std::move(bytes))});
    }
    const auto a = serial.execute(types, operations, implementations, "gr.bytes.sha256@1",
                                  "gr.cpu.sha256.oneshot@1", generated);
    const auto b = threaded.execute(types, operations, implementations, "gr.bytes.sha256@1",
                                    "gr.cpu.sha256.incremental@1", generated, options);
    check(a.outputs == b.outputs, "Seeded cross-provider and backend conformance");

    implementations.register_implementation(
        provider("test.lying-sha256@1", operations.describe("gr.bytes.sha256@1")),
        [](const Invocation &, std::stop_token) {
            return Invocation{Value::bytes("gr.sha256-hex@1", Bytes(64, '0'))};
        });
    const auto lie = serial.execute(types, operations, implementations, "gr.bytes.sha256@1",
                                    "test.lying-sha256@1", {batch[0]});
    check(text(lie.outputs[0][0]) != vectors[0].second,
          "Conformance detects a correct-shaped but semantically wrong provider");
    check(lie.metadata["validation_scope"].get<std::string>().find("not universal") != std::string::npos,
          "Execution success does not pretend universal semantic validation");
    implementations.register_implementation(
        provider("test.wrong-output-type@1", operations.describe("gr.bytes.sha256@1")),
        [](const Invocation &, std::stop_token) {
            return Invocation{Value::json("gr.json@1", "not bytes")};
        });
    fails("output_type", [&] {
        serial.execute(types, operations, implementations, "gr.bytes.sha256@1", "test.wrong-output-type@1",
                       {batch[0]});
    });
    implementations.register_implementation(
        provider("test.lying-identity@1", operations.describe("gr.bytes.identity@1")),
        [](const Invocation &, std::stop_token) { return Invocation{raw({42})}; });
    fails("postcondition", [&] {
        serial.execute(types, operations, implementations, "gr.bytes.identity@1", "test.lying-identity@1",
                       {batch[0]});
    });
}
void extension_and_effect_contracts() {
    ValueTypeRegistry types;
    gr::kernel::OperationRegistry operations;
    ImplementationRegistry implementations;
    types.register_type({"lab.pair@1",
                         Representation::Json,
                         "An ordered pair of exact bounded integers.",
                         {{"kind", "array"}, {"min_items", 2}, {"max_items", 2}}},
                        [](const Value &value) {
                            for (const auto &n : value.as_json())
                                if (!n.is_number_integer() || n < -100000 || n > 100000)
                                    throw gr::Error("pair_component",
                                                    "Expected bounded exact integer components.");
                        });
    OperationDescriptor operation{
        "lab.add-pairs@1",
        {"lab.pair@1", "lab.pair@1"},
        {"lab.pair@1", "gr.json@1"},
        Effect::Pure,
        Determinism::Exact,
        "Add two pairs componentwise, returning a pair and its declared dimension.",
        {"Each component sum is within the result type's interval [-100000, 100000]."},
        {"No component permutation; dimension is two."},
        Json::object()};
    fails("operation_type_contract", [&] { operations.register_operation(operation); });
    pin_types(operation, types);
    operations.register_operation(
        operation,
        [](const Invocation &in) {
            for (std::size_t i = 0; i < 2; ++i) {
                const auto sum = in[0].as_json()[i].get<int>() + in[1].as_json()[i].get<int>();
                if (sum < -100000 || sum > 100000)
                    throw gr::Error("pair_sum", "Pair sum exceeds the result type's range.");
            }
        },
        [](const Invocation &in, const Invocation &out) {
            for (std::size_t i = 0; i < 2; ++i)
                if (out[0].as_json()[i].get<int>() !=
                    in[0].as_json()[i].get<int>() + in[1].as_json()[i].get<int>())
                    throw gr::Error("postcondition", "Wrong component sum.");
            if (out[1].as_json() != Json{{"dimension", 2}})
                throw gr::Error("postcondition", "Wrong dimension metadata.");
        });
    implementations.register_implementation(
        provider("lab.direct-add@1", operation), [](const Invocation &args, std::stop_token) {
            return Invocation{
                Value::json("lab.pair@1",
                            Json::array({args[0].as_json()[0].get<int>() + args[1].as_json()[0].get<int>(),
                                         args[0].as_json()[1].get<int>() + args[1].as_json()[1].get<int>()})),
                Value::json("gr.json@1", {{"dimension", 2}})};
        });
    implementations.register_implementation(
        provider("lab.loop-add@1", operation), [](const Invocation &args, std::stop_token) {
            Json sums = args[0].as_json();
            for (std::size_t i = 0; i < sums.size(); ++i)
                sums[i] = sums[i].get<int>() + args[1].as_json()[i].get<int>();
            return Invocation{Value::json("lab.pair@1", std::move(sums)),
                              Value::json("gr.json@1", {{"dimension", 2}})};
        });
    SequentialBackend serial;
    ThreadedCpuBackend threaded;
    ExecutionOptions options;
    options.max_threads = 3;
    std::mt19937 random(20261013);
    Batch batch;
    for (int i = 0; i < 100; ++i)
        batch.push_back(
            {Value::json("lab.pair@1", Json::array({int(random() % 21) - 10, int(random() % 21) - 10})),
             Value::json("lab.pair@1", Json::array({int(random() % 21) - 10, int(random() % 21) - 10}))});
    const auto a =
        serial.execute(types, operations, implementations, operation.id, "lab.direct-add@1", batch);
    const auto b =
        threaded.execute(types, operations, implementations, operation.id, "lab.loop-add@1", batch, options);
    check(a.outputs == b.outputs,
          "External type, multi-input/multi-result operation and two providers need no core edits");
    auto swapped = batch;
    for (auto &args : swapped)
        std::swap(args[0], args[1]);
    check(
        serial.execute(types, operations, implementations, operation.id, "lab.loop-add@1", swapped).outputs ==
            a.outputs,
        "Declared pair addition commutativity checked without assuming all operations commute");
    auto bad = batch[0];
    bad[0] = Value::json("lab.pair@1", {"bad", 1});
    fails("pair_component", [&] {
        serial.execute(types, operations, implementations, operation.id, "lab.direct-add@1", {bad});
    });
    const Invocation overflow{Value::json("lab.pair@1", Json::array({100000, 0})),
                              Value::json("lab.pair@1", Json::array({1, 0}))};
    fails("pair_sum", [&] {
        serial.execute(types, operations, implementations, operation.id, "lab.direct-add@1", {overflow});
    });
    fails("duplicate_operation", [&] { operations.register_operation(operation); });

    int calls = 0;
    auto external = operation;
    external.id = "lab.external@1";
    external.effect = Effect::External;
    operations.register_operation(external);
    implementations.register_implementation(provider("lab.external-provider@1", external),
                                            [&](const Invocation &, std::stop_token) {
                                                ++calls;
                                                return Invocation{};
                                            });
    fails("unsupported_effect", [&] {
        serial.execute(types, operations, implementations, external.id, "lab.external-provider@1", {});
    });
    auto approximate = operation;
    approximate.id = "lab.approximate@1";
    approximate.determinism = Determinism::DeclaredApproximate;
    operations.register_operation(approximate);
    implementations.register_implementation(provider("lab.approximate-provider@1", approximate),
                                            [&](const Invocation &, std::stop_token) {
                                                ++calls;
                                                return Invocation{};
                                            });
    fails("unsupported_determinism", [&] {
        serial.execute(types, operations, implementations, approximate.id, "lab.approximate-provider@1", {});
    });
    check(calls == 0, "Unsupported effects and guarantees never run providers");
    auto changed = operation;
    changed.meaning += " Different contract.";
    gr::kernel::OperationRegistry other(false);
    other.register_operation(changed);
    fails("implementation_contract",
          [&] { serial.execute(types, other, implementations, changed.id, "lab.direct-add@1", {}); });
    ValueTypeRegistry redefined_types;
    auto redefined = types.describe("lab.pair@1");
    redefined.meaning = "A pair with different meaning under the same ID.";
    redefined_types.register_type(redefined);
    fails("operation_type_contract", [&] {
        serial.execute(redefined_types, operations, implementations, operation.id, "lab.direct-add@1", {});
    });
    fails("operation_type_contract", [&] {
        serial.execute(redefined_types, operations, implementations, operation.id, "lab.direct-add@1", batch);
    });
    auto repinned = operation;
    pin_types(repinned, redefined_types);
    check(repinned.fingerprint() != operation.fingerprint(),
          "Exact type descriptions are part of the operation fingerprint");
}
} // namespace
int main() {
    try {
        type_contracts();
        sha_conformance();
        extension_and_effect_contracts();
        std::cout << "operation conformance: " << checks
                  << " checks passed; bounded suites, not universal equivalence\n";
        return 0;
    } catch (const std::exception &error) {
        std::cerr << "operation conformance failure: " << error.what() << '\n';
        return 1;
    }
}
